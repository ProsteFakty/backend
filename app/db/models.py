    __tablename__ = "mp_news"

    term: Mapped[int] = mapped_column(primary_key=True)
    mp_id: Mapped[int] = mapped_column(primary_key=True)
    status: Mapped[str] = mapped_column(String(16))  # ok / empty / unavailable (= never fetched successfully)
    items: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, default=list)
